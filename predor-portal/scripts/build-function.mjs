// Bundles the portal into a single file for a Railway Function (Bun runtime),
// with the public/ assets embedded. Output: dist/function.tsx
import { build, transform } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';

const pub = path.resolve('public');
const types = { '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.svg': 'image/svg+xml', '.png': 'image/png', '.webmanifest': 'application/manifest+json' };
const files = {};
const SKIP = new Set(['icon-512.png']); // the manifest falls back to icon.svg for large sizes
for (const f of fs.readdirSync(pub)) {
  if (SKIP.has(f)) continue;
  const ext = path.extname(f);
  const type = types[ext] || 'application/octet-stream';
  const buf = fs.readFileSync(path.join(pub, f));
  if (ext === '.png') { files[`/${f}`] = { type, b64: buf.toString('base64') }; continue; }
  let text = buf.toString('utf8');
  if (ext === '.js') text = (await transform(text, { minify: true, format: 'esm', target: 'es2020' })).code;
  if (ext === '.css') text = (await transform(text, { loader: 'css', minify: true })).code;
  files[`/${f}`] = { type, text };
}
const embedded = `
const FILES = ${JSON.stringify(files)};
const cache = new Map();
function get(p) { if (!FILES[p]) return null; if (!cache.has(p)) cache.set(p, FILES[p].b64 ? Buffer.from(FILES[p].b64, 'base64') : Buffer.from(FILES[p].text, 'utf8')); return { type: FILES[p].type, body: cache.get(p) }; }
export function staticMiddleware() {
  return (req, res, next) => {
    if (req.method !== 'GET' && req.method !== 'HEAD') return next();
    const p = req.path === '/' ? '/index.html' : req.path;
    const f = get(p);
    if (!f) return next();
    res.setHeader('Content-Type', f.type);
    res.setHeader('Cache-Control', p.endsWith('.html') || p.endsWith('sw.js') ? 'no-cache' : 'public, max-age=3600');
    res.end(f.body);
  };
}
export function sendIndex(res) { const f = get('/index.html'); res.setHeader('Content-Type', f.type); res.setHeader('Cache-Control', 'no-cache'); res.end(f.body); }
`;
fs.mkdirSync('dist', { recursive: true });
fs.writeFileSync('dist/static-embedded.js', embedded);
await build({
  entryPoints: ['src/server.js'],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  outfile: 'dist/function.js',
  external: ['express', 'exceljs'],
  plugins: [{ name: 'static-alias', setup(b) { b.onResolve({ filter: /\/static\.js$/ }, () => ({ path: path.resolve('dist/static-embedded.js') })); } }],
  banner: { js: '// @ts-nocheck\n// Generated by scripts/build-function.mjs. Edit src/ and public/, then rebuild.' },
  legalComments: 'none',
  minify: true,
});
let out = fs.readFileSync('dist/function.js', 'utf8');
out = out.replace(/from "express"/g, 'from "express@4.21.2"').replace(/from "exceljs"/g, 'from "exceljs@4.4.0"');
fs.writeFileSync('dist/function.tsx', out);
console.log('dist/function.tsx', (out.length / 1024).toFixed(1), 'KB');
